    expect(QR_PREFIXES.HYBRID_PQ).toBe('HYBRID-PQ:');
    expect(QR_PREFIXES.DURESS).toBe('DURESS:');
    expect(QR_PREFIXES.MEOW_CHUNKED).toBe('MEOW-');
